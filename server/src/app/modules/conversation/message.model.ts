import { InferSchemaType, model, Schema } from "mongoose";
import { CHAT_LIMITS, MESSAGE_KINDS, SYSTEM_MESSAGE_TYPES } from "./conversation.constant";

/** A file shared in chat (uploaded with context `chat_attachment`, attached to the conversation). */
const attachmentSchema = new Schema(
  {
    fileId: { type: Schema.Types.ObjectId, ref: "File", required: true },
    /** Private files: `/files/:id/url` (the client asks for a 10-min signed URL). */
    url: { type: String, required: true },
    name: { type: String, required: true },
    mime: { type: String, required: true },
    size: { type: Number, required: true },
  },
  { _id: false },
);

/**
 * A single chat message. Pagination is by `_id` (ObjectIds grow with time), so no `skip()` on long threads.
 *
 * Deleting: the sender deletes for everyone (`isDeleted`, content cleared, a placeholder stays in the thread);
 * the other side can only hide it for themselves (`hiddenFor`).
 */
const messageSchema = new Schema(
  {
    conversationId: { type: Schema.Types.ObjectId, ref: "Conversation", required: true },
    /** null for `system` messages. */
    senderId: { type: Schema.Types.ObjectId, ref: "User", default: null },
    kind: { type: String, enum: MESSAGE_KINDS, required: true, default: "text" },
    text: { type: String, maxlength: CHAT_LIMITS.maxTextLength, default: "" },
    attachments: { type: [attachmentSchema], default: undefined },
    /** Set when `kind === "offer"`. */
    offerId: { type: Schema.Types.ObjectId, ref: "Offer" },
    /** Set when `kind === "system"` — what the notice is about (styles the notice in the UI). */
    systemType: { type: String, enum: SYSTEM_MESSAGE_TYPES },
    /** Extra data for system notices, e.g. `{ offerId, orderId, title, priceCents }`. */
    systemPayload: { type: Schema.Types.Mixed },
    isDeleted: { type: Boolean, default: false },
    hiddenFor: { type: [Schema.Types.ObjectId], default: undefined },
    /**
     * Random id generated by the client per message. A retried request (flaky network)
     * hits the unique index below and returns the first copy instead of a duplicate.
     */
    clientMsgId: { type: String, maxlength: 64 },
  },
  { timestamps: { createdAt: true, updatedAt: false }, versionKey: false },
);

// Thread page: newest first, `before=<messageId>` cursor.
messageSchema.index({ conversationId: 1, _id: -1 });
// Retry-safe sends (only rows that carry a clientMsgId).
messageSchema.index(
  { conversationId: 1, senderId: 1, clientMsgId: 1 },
  { unique: true, partialFilterExpression: { clientMsgId: { $type: "string" } } },
);

export type IMessage = InferSchemaType<typeof messageSchema>;
export const Message = model("Message", messageSchema, "messages");
